"""Generate the MuJoCo site model from the V2 planning-box export (MuJoCo plant spec Section 3.1, plan Task 2).

Every box of construction_site_v2.boxes.yaml becomes a static box geom `site/<export name>` (class `site`: contype 1,
conaffinity 2, group 0, so it collides with the robot's geoms but not with other site geoms), plus a ground plane.
The boxes file's SHA-256 (site_checksum), the map PGM's SHA-256 from the map metadata and the generator version are
embedded as custom text. Nothing is placed by hand.

    python3 tools/plant/generate_site_model.py           # (re)write ros2_ws/src/mobile_manipulator_plant/models/site_v2.xml
    python3 tools/plant/generate_site_model.py --check   # exit 1 if the committed model is not current
"""
import argparse
import hashlib
import json
import math
import sys
from pathlib import Path

import numpy as np
import yaml

ROOT = Path(__file__).resolve().parents[2]
MAPS = ROOT / "ros2_ws/src/mobile_manipulator_navigation/maps"
BOXES = MAPS / "construction_site_v2.boxes.yaml"
METADATA = MAPS / "construction_site_v2.metadata.json"
OUTPUT = ROOT / "ros2_ws/src/mobile_manipulator_plant/models/site_v2.xml"
GENERATOR = "generate_site_model 1"

# Nav2MapGeometry.CellBoundaryTolerance (cells)
CELL_TOLERANCE = 1e-4
# The export writes yaw with 4 decimals: half a unit of its last digit.
YAW_ROUNDING = 5e-5


def unity_yaw(yaw):
    """The yaw Unity rasterized the map at: an exported yaw within the export's rounding of a multiple of pi/2 is that
    multiple (90 degrees is exported as 1.5708). The MuJoCo geoms keep the exported yaw, as B5's world does."""
    k = round(yaw / (math.pi / 2))
    return k * (math.pi / 2) if abs(yaw - k * (math.pi / 2)) <= YAW_ROUNDING else yaw


def num(value):
    """Shortest round-trip text of a float (integers without a trailing .0 noise)."""
    return repr(float(value))


def generate_site(boxes_path, metadata_path):
    boxes = yaml.safe_load(Path(boxes_path).read_text())["boxes"]
    meta = json.loads(Path(metadata_path).read_text())
    checksum = "sha256:" + hashlib.sha256(Path(boxes_path).read_bytes()).hexdigest()
    lines = [
        '<mujoco model="site_v2">',
        f"  <!-- Generated by tools/plant/generate_site_model.py from {Path(boxes_path).name}; do not edit. -->",
        '  <compiler angle="radian"/>',
        "  <custom>",
        f'    <text name="site_checksum" data="{checksum}"/>',
        f'    <text name="map_pgm_sha256" data="{meta["pgmSha256"]}"/>',
        f'    <text name="generator" data="{GENERATOR}"/>',
        "  </custom>",
        "  <default>",
        '    <default class="site">',
        '      <geom type="box" contype="1" conaffinity="2" group="0" rgba="0.62 0.62 0.6 1"/>',
        "    </default>",
        "  </default>",
        "  <worldbody>",
        '    <geom name="ground" type="plane" size="0 0 0.05" contype="1" conaffinity="2" group="0" rgba="0.45 0.42 0.38 1"/>',
    ]
    for box in boxes:
        yaw = float(box["yaw"])
        pos = " ".join(num(v) for v in box["center"])
        size = " ".join(num(v / 2) for v in box["size"])
        quat = " ".join(num(v) for v in (math.cos(yaw / 2), 0.0, 0.0, math.sin(yaw / 2)))
        lines.append(f'    <geom name="site/{box["name"]}" class="site" pos="{pos}" size="{size}" quat="{quat}"/>')
    lines += ["  </worldbody>", "</mujoco>", ""]
    return "\n".join(lines)


def box_xy_bounds(box):
    """Axis-aligned x/y bounds of a box yawed about the vertical, at the yaw Unity used."""
    cx, cy, _ = box["center"]
    hx, hy = box["size"][0] / 2, box["size"][1] / 2
    yaw = unity_yaw(box["yaw"])
    c, s = abs(math.cos(yaw)), abs(math.sin(yaw))
    ex, ey = c * hx + s * hy, s * hx + c * hy
    return cx - ex, cx + ex, cy - ey, cy + ey


def in_band(box, meta):
    z, hz = box["center"][2], box["size"][2] / 2
    return z + hz > meta["minimumUnityHeight"] and z - hz < meta["maximumUnityHeight"]


def cell_range(lo, hi, origin, resolution, count):
    first = math.floor((lo - origin) / resolution + CELL_TOLERANCE)
    last = math.ceil((hi - origin) / resolution - CELL_TOLERANCE) - 1
    return max(0, min(first, count - 1)), max(0, min(last, count - 1))


def rasterize(boxes, meta):
    """Occupancy (rows = y from the map's lowest, columns = x) by Nav2MapExporter's rule (Nav2MapGeometry)."""
    width, height, res = meta["widthCells"], meta["heightCells"], meta["resolutionMetres"]
    ox, oy = meta["originRosX"], meta["originRosY"]
    occupied = np.zeros((height, width), dtype=bool)
    for box in boxes:
        if not in_band(box, meta):
            continue
        x0, x1, y0, y1 = box_xy_bounds(box)
        if x1 <= ox or x0 >= ox + width * res or y1 <= oy or y0 >= oy + height * res:
            continue
        c0, c1 = cell_range(x0, x1, ox, res, width)
        r0, r1 = cell_range(y0, y1, oy, res, height)
        if c0 <= c1 and r0 <= r1:
            occupied[r0:r1 + 1, c0:c1 + 1] = True
    return occupied


def cells_on_box_edges(boxes, meta, tolerance_cells):
    """(row, column) cells next to a band box's bounds edge that lies within tolerance_cells of a cell boundary:
    where float rounding decides between two cells."""
    res, ox, oy = meta["resolutionMetres"], meta["originRosX"], meta["originRosY"]
    cells = set()
    for box in boxes:
        if not in_band(box, meta):
            continue
        x0, x1, y0, y1 = box_xy_bounds(box)
        c0, c1 = cell_range(x0, x1, ox, res, meta["widthCells"])
        r0, r1 = cell_range(y0, y1, oy, res, meta["heightCells"])
        for edge, axis in ((x0, "x"), (x1, "x"), (y0, "y"), (y1, "y")):
            origin = ox if axis == "x" else oy
            f = (edge - origin) / res
            if abs(f - round(f)) > tolerance_cells:  # inside a cell: rounding cannot move it
                continue
            k = round(f)
            if axis == "x":
                cells |= {(r, c) for r in range(r0 - 1, r1 + 2) for c in (k - 1, k)}
            else:
                cells |= {(r, c) for r in (k - 1, k) for c in range(c0 - 1, c1 + 2)}
    return cells


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="exit 1 if the committed model is not current")
    args = parser.parse_args()
    text = generate_site(BOXES, METADATA)
    if args.check:
        current = OUTPUT.exists() and OUTPUT.read_text() == text
        print("site model current" if current else f"{OUTPUT.relative_to(ROOT)} is not current")
        return 0 if current else 1
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(text)
    print(f"wrote {OUTPUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
